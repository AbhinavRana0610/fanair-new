  <script>
    function toggleEmailModal(show) {
      const emModal = document.getElementById('emailModal');
      if (emModal) {
        if (show) {
          emModal.classList.add('active');
          emModal.style.display = 'flex';
        } else {
          emModal.classList.remove('active');
          emModal.style.display = 'none';
        }
      }
    }

    document.addEventListener('DOMContentLoaded', function() {
      const emForm = document.getElementById('emailForm');
      const emModal = document.getElementById('emailModal');

      if (emModal) {
        emModal.addEventListener('click', function(e) {
          if (e.target === emModal) {
            toggleEmailModal(false);
          }
        });
      }

      // Ensure all videos play silently and smoothly
      document.querySelectorAll('video').forEach(function(v) {
        v.muted = true;
        v.defaultMuted = true;
        v.volume = 0;
      });

      const cardVideo = document.querySelector('.about-card--right video');
      if (cardVideo) {
        cardVideo.muted = true;
        const playCardVideo = () => {
          cardVideo.play().catch(() => {});
        };
        playCardVideo();
        ['touchstart', 'click', 'scroll'].forEach(evt => {
          window.addEventListener(evt, playCardVideo, { once: true, passive: true });
        });
      }
    });
  </script>
